import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";

test("build emits a standalone BetterDiscord plugin with metadata and bundled features", async () => {
  const output = await readFile(new URL("../dist/BarklyAccess.plugin.js", import.meta.url), "utf8");
  assert.match(output, /@name\s+BarklyAccess/);
  assert.match(output, /@author\s+Barkly Labs/);
  assert.match(output, /module\.exports/);
  assert.match(output, /buildFrequentContacts/);
  assert.match(output, /normalizeMessages/);
  assert.match(output, /Open Analytics Dashboard/);
  assert.match(output, /ba-analytics-dashboard/);
  assert.match(output, /data-dashboard-conversations/);
  assert.match(output, /aria-modal/);
  assert.match(output, /aria-labelledby/);
  assert.match(output, /type="date"/);
  assert.match(output, /data-page-next/);
  assert.match(output, /Higher contrast/);
  assert.match(output, /ba-frequent-search/);
  assert.match(output, /ba-frequent-sort/);
  assert.match(output, /ba-contact-link/);
  assert.match(output, /createDiscordConversationLink/);
  assert.match(output, /ba-contact-fallback/);
  assert.match(output, /rendered-discord-ui/);
  assert.match(output, /HistoricalStore/);
  assert.match(output, /prefers-reduced-motion/);
  assert.match(output, /ba-collection-popup/);
  assert.match(output, /aria-live="polite"/);
  assert.match(output, /data-popup-cancel/);
  assert.match(output, /initial_completed/);
  assert.match(output, /My Messages/);
  assert.match(output, /Other Participant's Messages/);
  assert.match(output, /Compare Activity/);
  assert.match(output, /ba-control-size/);
  assert.match(output, /incremental-visible-batch/);
  assert.doesNotMatch(output, /require\(["'](?:esbuild|\.\.\/\.\.\/core)/);
  const module = { exports: {} };
  vm.runInNewContext(output, { module, exports: module.exports });
  assert.equal(typeof module.exports, "function");
  const plugin = new module.exports();
  assert.equal(typeof plugin.start, "function");
  assert.equal(typeof plugin.stop, "function");
});
